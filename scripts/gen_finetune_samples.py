def build_input(variant: dict, arch: dict) -> str:
    feats = arch.get("适用素材特征") or {}
    emo = "/".join(feats.get("情绪基调") or [])
    parts = [
        f"素材特征：时长={variant['时长秒']}秒",
        f"表现形式={variant['表现形式']}",
        f"内容={variant['内容描述']}",
    ]
    if variant.get("问句数"):
        parts.append(f"含{variant['问句数']}个问句")
    parts.append(f"前3秒={variant['前3秒']}")
    parts.append("关键词=" + "/".join(variant["关键词"]))
    if variant.get("场景"):
        parts.append(f"场景={variant['场景']}")
    if emo:
        parts.append(f"情绪基调={emo}")
    if variant.get("关键信息点数"):
        parts.append(f"关键信息点约{variant['关键信息点数']}个")
    return "，".join(parts)


