def parse_percent(s: str) -> float:
    """把 '8-12%' / '15%' / '60-70%' 解析为占比（0-100），取区间中值。"""
    if not isinstance(s, str):
        return 10.0
    nums = re.findall(r"\d+(?:\.\d+)?", s)
    if not nums:
        return 10.0
    vals = [float(n) for n in nums]
    return sum(vals) / len(vals)


def distribute_segments(segments: list[dict], total_sec: float) -> list[tuple[float, float]]:
    """按段落时长占比把总秒数切成 (start, end)，最后一段收尾到 total_sec。"""
    percents = [parse_percent(seg.get("时长占比", "10%")) for seg in segments]
    s = sum(percents) or 1.0
    bounds: list[tuple[float, float]] = []
    cursor = 0.0
    for i, p in enumerate(percents):
        length = total_sec * (p / s)
        start = cursor
        end = total_sec if i == len(percents) - 1 else cursor + length
        bounds.append((round(start, 1), round(end, 1)))
        cursor = end
    return bounds


def build_reason(arch: dict, variant: dict) -> str:
    """基于架构档案的匹配规则/适用素材特征 + 变体素材特征，生成真实决策理由。"""
    mr = arch.get("匹配规则") or {}
    kws = mr.get("匹配关键词") or []
    feat = arch.get("适用素材特征") or {}
    hits = [kw for kw in kws if kw in variant["全文本信号"]]
    parts = [f"素材{variant['理由素材描述']}，符合「{arch.get('名称','')}」的核心特征——{arch.get('描述','')[:60]}"]
    if hits:
        parts.append(f"文本命中关键信号词：{('/'.join(hits[:4]))}")
    if mr.get("需要问句") and variant.get("问句数", 0) > 0:
        parts.append(f"含{variant['问句数']}个问句，满足该架构对连续提问/信息缺口的要求")
    if mr.get("需要对比词") and variant.get("对比词"):
        parts.append(f"含对比信号（{variant['对比词']}），符合并列反差结构")
    if mr.get("需要步骤词") and variant.get("步骤词"):
        parts.append(f"含步骤/流程信号（{variant['步骤词']}），符合分步交付结构")
    if mr.get("需要情绪词") and variant.get("情绪词"):
        parts.append(f"含情绪触发点（{variant['情绪词']}），符合情绪曲线")
    ct = feat.get("内容类型") or []
    if ct:
        parts.append(f"内容类型属{('/'.join(ct[:3]))}范畴")
    return "；".join(parts)


