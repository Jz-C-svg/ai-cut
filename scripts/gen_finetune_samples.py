def build_sample(arch_id: str, arch: dict, variant: dict, film_lang: dict,
                 hard_info: str | None = None) -> dict:
    """用真实架构档案字段 + 变体素材特征，构造一条微调样本。
    hard_info: 若为困难案例，传入 common_mistake 文本，output 标注 difficulty=hard。"""
    total = float(variant["时长秒"])
    segments = arch.get("段落序列") or []
    bounds = distribute_segments(segments, total)

    段落计划 = []
    for seg, (st, en) in zip(segments, bounds):
        段落计划.append({
            "段落功能": seg.get("功能", ""),
            "时长占比": seg.get("时长占比", ""),
            "信息密度": seg.get("信息密度", ""),
            "节奏": seg.get("节奏", ""),
            "剪辑要点": seg.get("剪辑要点", "") or seg.get("描述", ""),
            "对应素材": f"{st}-{en}秒",
        })

    decision = {
        "matched_arch": arch_id,
        "content_layer": arch.get("content_layer", arch.get("层级", "shortform")),
        "架构名称": arch.get("名称", ""),
        "匹配理由": build_reason(arch, variant),
        "段落计划": 段落计划,
        "剪辑语言应用点": build_clip_points(arch, film_lang),
        "钩子设计": build_hook_design(arch, variant),
        "CTA设计": build_cta_design(arch, variant),
    }
    if hard_info:
        decision["difficulty"] = "hard"
        decision["common_mistake"] = hard_info
    return {
        "instruction": INSTRUCTION,
        "input": build_input(variant, arch),
        "output": {"architecture_decision": decision},
    }


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    film_lang = arch_mod.load_film_language() or {}

    index = arch_mod.available_architectures()
    samples: list[dict] = []
    per_arch_count: dict[str, int] = {}
    input_lens: list[int] = []
    output_lens: list[int] = []
    hard_count = 0

    for item in index:
        arch_id = item.get("id")
        arch = arch_mod.load_architecture(arch_id)
        if not arch:
            print(f"[警告] 无法加载架构档案：{arch_id}")
            continue
        variants = list(VARIANTS.get(arch_id, [])) + list(VARIANTS_EXTRA.get(arch_id, []))
        if not variants:
            print(f"[提示] 架构 {arch_id} 无预定义变体，跳过（可在 VARIANTS 补充）")
            continue
        for variant in variants:
            sample = build_sample(arch_id, arch, variant, film_lang)
            samples.append(sample)
            per_arch_count[arch_id] = per_arch_count.get(arch_id, 0) + 1
            input_lens.append(len(sample["input"]))
            output_lens.append(len(json.dumps(sample["output"], ensure_ascii=False)))

    # 困难案例（边界易误判）
    hard_by_arch: dict[str, int] = {}
    for arch_id, variant, mistake in HARD_CASES:
        arch = arch_mod.load_architecture(arch_id)
        if not arch:
            continue
        sample = build_sample(arch_id, arch, variant, film_lang, hard_info=mistake)
        samples.append(sample)
        per_arch_count[arch_id] = per_arch_count.get(arch_id, 0) + 1
        hard_by_arch[arch_id] = hard_by_arch.get(arch_id, 0) + 1
        hard_count += 1
        input_lens.append(len(sample["input"]))
        output_lens.append(len(json.dumps(sample["output"], ensure_ascii=False)))

    # 写 JSONL
    with SAMPLES_FILE.open("w", encoding="utf-8") as f:
        for s in samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    meta = {
        "样本总数": len(samples),
        "覆盖架构数": len(per_arch_count),
        "各架构样本数": per_arch_count,
        "平均输入长度": round(statistics.mean(input_lens), 1) if input_lens else 0,
        "平均输出长度": round(statistics.mean(output_lens), 1) if output_lens else 0,
        "字段说明": {
            "instruction": "固定系统指令：专业短视频剪辑师角色",
            "input": "素材特征（时长/表现形式/内容/问句/前3秒/关键词/场景/情绪）",
            "output.architecture_decision": {
                "matched_arch": "匹配的架构 id",
                "content_layer": "shortform/longform",
                "匹配理由": "基于素材特征+架构匹配规则的推理",
                "段落计划": "从架构档案段落序列读取，时长占比按总时长换算为秒",
                "剪辑语言应用点": "转场/字幕/BGM/景别建议，来自架构档案+film-language",
                "钩子设计": "来自架构档案钩子规则",
                "CTA设计": "来自架构档案CTA规则",
            },
        },
        "生成时间": __import__("time").strftime("%Y-%m-%d %H:%M:%S"),
        "困难案例数": hard_count,
        "困难案例分布": hard_by_arch,
        "困难案例说明": "difficulty=hard 的边界易误判样本，output 含 common_mistake 常见误判方向",
    }
    META_FILE.write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"[完成] 生成 {len(samples)} 条样本（含困难案例 {hard_count} 条）→ {SAMPLES_FILE}")
    print(f"[完成] 元数据 → {META_FILE}")
    print(f"[统计] 平均输入 {meta['平均输入长度']} 字，平均输出 {meta['平均输出长度']} 字符")
    for aid, n in per_arch_count.items():
        print(f"  - {aid}: {n} 条")


if __name__ == "__main__":
    main()
